        for s in me.earnings_states(rows, field=잣):
            폭 = s.get("신고점폭")
            if 폭 is not None:
                전체 += 1
                if 앞ttm is None:
                    끊김 += 1
                    if 폭 > 최대:
                        최대, 종목 = 폭, f"{t} {s['announced']}"
            # 183차-E — **신호 단위**로도 셉니다. 칸 수만으로는 이것이
