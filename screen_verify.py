# 183차-S — "일감"이라 부르던 칸의 **거의 전부가 고칠 수 없는 것**이었습니다
# ---------------------------------------------------------------------------
# 화면은 "못 붙였고 그 회사는 냄 1,746 ← 일감" 이라고 적어 왔습니다. 주인이
# 읽으면 1,746칸을 고칠 수 있다는 말로 들립니다. 전수로 갈라 보니:
