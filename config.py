def fmt_amount(value, basis: str = BASIS_OP_INCOME, digits: int = 1) -> str:
    """기준자에 맞는 단위로 금액을 씁니다.

    같은 함수를 쓰지 않으면 조정 EPS 8.53 달러가 화면에 "$0M" 으로 나옵니다
    (백만 단위로 나눠 버리므로). 실제로 그렇게 나왔습니다.
    """
    if value is None:
        return "-"
    if basis == BASIS_ADJ_EPS:
        return f"${value:,.2f}/주"
    return f"${value / 1e6:,.{digits}f}M"


def quarters_basis(quarters: list) -> str:
    """분기 자료가 어느 기준자로 채워져 있는지 알려 줍니다.

    기준자는 수집 단계(pipeline)에서 정해 각 분기에 적어 둡니다.
    표시가 없으면 지금까지처럼 논갭 영업이익으로 봅니다.
    """
    for quarter in reversed(quarters or []):
        basis = quarter.get("basis")
        if basis:
            return basis
    return BASIS_OP_INCOME

